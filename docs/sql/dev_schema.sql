-- The whole ProfitSync table setup in one file, copied from the live
-- database's structure on 2026-11-21 (structure only, no data).
-- Use it to set up a fresh, empty database such as the dev project
-- "profitsync-dev". Do NOT run it on the live database.
-- Every table is locked down: only ProfitSync's server (the "postgres" owner
-- role) can read or write them, not the public Supabase API.

CREATE TABLE IF NOT EXISTS public."ebayConnection" (
  id                      serial PRIMARY KEY,
  "accessToken"           text NOT NULL,
  "accessTokenExpiresAt"  timestamptz NOT NULL,
  "createdAt"             timestamptz NOT NULL DEFAULT now(),
  "refreshToken"          text NOT NULL,
  "refreshTokenExpiresAt" timestamptz NOT NULL,
  "updatedAt"             timestamptz NOT NULL,
  "ebayUserId"            text NULL,
  environment             text NOT NULL DEFAULT 'SANDBOX',
  "userId"                text NULL,
  "ebayUsername"          text NULL,
  "storeName"             text NULL,
  "lastOrderSyncAt"       timestamptz NULL,
  "lastFullOrderSyncAt"   timestamptz NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "ebayConnection_environment_ebayUserId_unique"
  ON public."ebayConnection" (environment, "ebayUserId") WHERE "ebayUserId" IS NOT NULL;
CREATE INDEX IF NOT EXISTS ebay_connection_user_idx ON public."ebayConnection" ("userId", environment);

CREATE TABLE IF NOT EXISTS public."order" (
  id                   serial PRIMARY KEY,
  "createdAt"          timestamptz NOT NULL DEFAULT now(),
  "ebayFees"           numeric NOT NULL,
  "ebayOrderId"        text NULL UNIQUE,
  item                 text NOT NULL,
  "orderDate"          timestamptz NOT NULL DEFAULT now(),
  "productCost"        numeric NULL,
  "salePrice"          numeric NOT NULL,
  status               text NOT NULL DEFAULT 'COST_NEEDED',
  "updatedAt"          timestamptz NOT NULL,
  "ebayUserId"         text NULL,
  "userId"             text NULL,
  environment          text NULL DEFAULT 'SANDBOX',
  "ebayBuyerId"        text NULL,
  "imageUrl"           text NULL,
  "refundAmount"       numeric NULL,
  "refundedAt"         timestamptz NULL,
  "refundOutcome"      text NULL,
  "refundShippingLoss" numeric(12,2) NOT NULL DEFAULT 0,
  "refundFeeLoss"      numeric(12,2) NOT NULL DEFAULT 0,
  "ebayItemId"         text NULL,
  "ebayVariationId"    text NULL,
  sku                  text NULL,
  quantity             integer NOT NULL DEFAULT 1,
  "shippingLabelCost"  numeric(12,2) NULL,
  "shippingCost"       numeric(12,2) NULL,
  "otherFees"          numeric(12,2) NULL,
  CONSTRAINT order_refund_outcome_valid CHECK ("refundOutcome" IS NULL OR "refundOutcome" IN ('NOT_SHIPPED', 'SHIPPED_LOST', 'RETURNED')),
  CONSTRAINT "order_shippingCost_check" CHECK ("shippingCost" IS NULL OR "shippingCost" >= 0)
);
CREATE INDEX IF NOT EXISTS "order_ebayBuyerId_environment_idx" ON public."order" ("ebayBuyerId", environment) WHERE "ebayBuyerId" IS NOT NULL;
CREATE INDEX IF NOT EXISTS "order_ebayUserId_environment_idx" ON public."order" ("ebayUserId", environment) WHERE "ebayUserId" IS NOT NULL;
CREATE INDEX IF NOT EXISTS order_user_date_idx ON public."order" ("userId", "orderDate" DESC);
CREATE INDEX IF NOT EXISTS order_user_store_date_idx ON public."order" ("userId", "ebayUserId", "orderDate" DESC);

CREATE TABLE IF NOT EXISTS public."EbayListing" (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"           text NOT NULL,
  "ebayUserId"       text NOT NULL,
  environment        text NOT NULL DEFAULT 'PRODUCTION',
  "ebayItemId"       text NOT NULL,
  title              text NOT NULL,
  sku                text NULL,
  "imageUrl"         text NULL,
  "listingPrice"     numeric NOT NULL,
  quantity           integer NOT NULL DEFAULT 0,
  status             text NOT NULL DEFAULT 'ACTIVE',
  "createdAt"        timestamptz NOT NULL DEFAULT now(),
  "updatedAt"        timestamptz NOT NULL DEFAULT now(),
  "unitCost"         numeric(12,2) NULL CHECK ("unitCost" IS NULL OR "unitCost" >= 0),
  "shippingCost"     numeric(12,2) NULL CHECK ("shippingCost" IS NULL OR "shippingCost" >= 0),
  "watchCount"       integer NULL,
  "listedAt"         timestamptz NULL,
  views30            integer NULL,
  impressions30      integer NULL,
  sales30            integer NULL,
  "trafficUpdatedAt" timestamptz NULL,
  "categoryName"     text NULL,
  "categoryPath"     text NULL,
  brand              text NULL,
  "detailsCheckedAt" timestamptz NULL,
  CONSTRAINT "EbayListing_unique_account_item" UNIQUE ("userId", "ebayUserId", environment, "ebayItemId")
);

CREATE TABLE IF NOT EXISTS public."ebayDeletedAccount" (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  environment   text NOT NULL,
  "ebayUserId"  text NULL,
  "deletedAt"   timestamptz NOT NULL DEFAULT now(),
  "accountHash" text NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "ebayDeletedAccount_environment_accountHash_idx"
  ON public."ebayDeletedAccount" (environment, "accountHash") WHERE "accountHash" IS NOT NULL;

CREATE TABLE IF NOT EXISTS public."ebayDeletedIdentifier" (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  environment      text NOT NULL,
  "identifierHash" text NOT NULL,
  "createdAt"      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (environment, "identifierHash")
);

CREATE TABLE IF NOT EXISTS public."ebayDeletionEvent" (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  "notificationId" text NOT NULL,
  environment      text NOT NULL,
  "processedAt"    timestamptz NOT NULL DEFAULT now(),
  UNIQUE ("notificationId", environment)
);

CREATE TABLE IF NOT EXISTS public.expense (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  "userId"        text NOT NULL,
  "ebayUserId"    text NULL,
  "spentOn"       date NOT NULL,
  category        text NOT NULL,
  amount          numeric(12,2) NOT NULL CHECK (amount >= 0),
  note            text NULL,
  "createdAt"     timestamptz NOT NULL DEFAULT now(),
  "repeatMonthly" boolean NOT NULL DEFAULT false,
  "endedOn"       date NULL,
  "ebayChargeKey" text NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS expense_ebay_charge_key_idx
  ON public.expense ("userId", "ebayUserId", "ebayChargeKey") WHERE "ebayChargeKey" IS NOT NULL;
CREATE INDEX IF NOT EXISTS expense_user_date_idx ON public.expense ("userId", "spentOn");

CREATE TABLE IF NOT EXISTS public.purchase (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  "userId"      text NOT NULL,
  "ebayUserId"  text NULL,
  "purchasedOn" date NOT NULL,
  source        text NOT NULL,
  note          text NULL,
  "createdAt"   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS purchase_user_date_idx ON public.purchase ("userId", "purchasedOn");

CREATE TABLE IF NOT EXISTS public."inventoryItem" (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  "userId"     text NOT NULL,
  "purchaseId" bigint NOT NULL REFERENCES public.purchase (id) ON DELETE CASCADE,
  name         text NOT NULL,
  quantity     integer NOT NULL CHECK (quantity >= 1),
  "unitCost"   numeric(12,2) NOT NULL CHECK ("unitCost" >= 0),
  "ebayItemId" text NULL,
  "createdAt"  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS inventory_item_purchase_idx ON public."inventoryItem" ("purchaseId");
CREATE INDEX IF NOT EXISTS inventory_item_user_listing_idx ON public."inventoryItem" ("userId", "ebayItemId");

CREATE TABLE IF NOT EXISTS public.subscription (
  "userId"               text PRIMARY KEY,
  "stripeCustomerId"     text NULL UNIQUE,
  "stripeSubscriptionId" text NULL UNIQUE,
  plan                   text NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'pro', 'ultimate')),
  "billingInterval"      text NULL CHECK ("billingInterval" IN ('month', 'year')),
  status                 text NULL,
  "currentPeriodEnd"     timestamptz NULL,
  "cancelAtPeriodEnd"    boolean NOT NULL DEFAULT false,
  comped                 boolean NOT NULL DEFAULT false,
  "createdAt"            timestamptz NOT NULL DEFAULT now(),
  "updatedAt"            timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."rateLimit" (
  key           text PRIMARY KEY,
  "windowStart" timestamptz NOT NULL DEFAULT now(),
  count         integer NOT NULL DEFAULT 0
);

-- Lock everything down.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['ebayConnection', 'order', 'EbayListing', 'ebayDeletedAccount', 'ebayDeletedIdentifier',
                           'ebayDeletionEvent', 'expense', 'purchase', 'inventoryItem', 'subscription', 'rateLimit']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t);
  END LOOP;
END $$;
